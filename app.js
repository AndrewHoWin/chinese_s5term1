    init() {
        const totalW = Object.values(window.CLASSICAL_DATABASE).reduce((acc, l) => acc + l.words.length, 0);
        const totalS = Object.values(window.CLASSICAL_DATABASE).reduce((acc, l) => acc + l.sentences.length, 0);
        const badge = document.getElementById("questionCountStatus");
        badge.textContent = `✅ 題庫已就緒：詞語精解 ${totalW} 題 · 全句解析 ${totalS} 題`;

        window.addEventListener("keydown", (e) => {
            if (!document.getElementById("quizView").classList.contains("active")) return;
            if (e.key === "ArrowLeft") {
                this.prevQuestion();
            } else if (e.key === "ArrowRight") {
                this.nextQuestion();
            } else if (e.key === " ") {
                e.preventDefault();
                const q = this.activeQuestions[this.currentIndex];
                if (q && !this.revealedState[q.id]) {
                    this.revealAnswer();
                }
            } else if (e.key === "1") {
                const q = this.activeQuestions[this.currentIndex];
                if (q && this.revealedState[q.id]) {
                    this.markResult(true);
                }
            } else if (e.key === "2") {
                const q = this.activeQuestions[this.currentIndex];
                if (q && this.revealedState[q.id]) {
                    this.markResult(false);
                }
            }
        });
    }

    switchView(viewId) {
        document.querySelectorAll(".view-page").forEach(el => el.classList.remove("active"));
        document.getElementById(viewId).classList.add("active");
        window.scrollTo({ top: 0, behavior: "smooth" });
    }

    shuffle(arr) {
        const copy = [...arr];
        for (let i = copy.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [copy[i], copy[j]] = [copy[j], copy[i]];
        }
        return copy;
    }

    escapeHtml(str) {
        if (str === null || str === undefined) return "";
        return String(str)
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

