    highlightWordInSentence(sentence, targetWord) {
        const escapedSent = this.escapeHtml(sentence);
        const escapedWord = this.escapeHtml(targetWord);
        const idx = escapedSent.indexOf(escapedWord);
        if (idx === -1) {
            return `${escapedSent} <span class="hl-word">【${escapedWord}】</span>`;
        }
        return (
            escapedSent.slice(0, idx) +
            `<span class="hl-word">${escapedWord}</span>` +
            escapedSent.slice(idx + escapedWord.length)
        );
    }

    buildQuestionBank() {
        let wId = 1;
        let sId = 1;

        MASTER_SENTENCES.forEach(item => {
            // 1. 生成「第二部分：全句語法修辭全析」題目
            this.sentenceQuestions.push({
                id: `S-${sId++}`,
                mode: "sentence",
                paperId: item.paperId,
                paperName: item.paperName,
                num: item.num,
                sentence: item.sentence,
                trans: item.trans,
                allWords: item.allWords,
                funcWords: item.funcWords,
                patterns: item.patterns,
                usages: item.usages,
                archaic: item.archaic,
                loans: item.loans,
                rhetoric: item.rhetoric
            });

            // 2. 生成「第一部分：抽取句中高亮詞語解釋與作用」題目
            if (Array.isArray(item.words)) {
                item.words.forEach((wObj, wIdx) => {
                    this.wordQuestions.push({
                        id: `W-${wId++}`,
                        mode: "word",
                        paperId: item.paperId,
                        paperName: item.paperName,
                        num: item.num,
                        subNum: wIdx + 1,
                        sentence: item.sentence,
                        targetWord: wObj.w,
                        wordMeaning: wObj.m,
                        trans: item.trans,
                        allWords: item.allWords,
                        funcWords: item.funcWords,
                        patterns: item.patterns
                    });
                });
            }
        });
    }

    init() {
        const badge = document.getElementById("questionCountStatus");
        if (badge) {
            const totalW = this.wordQuestions.length;
            const totalS = this.sentenceQuestions.length;
            badge.textContent = `✅ 題庫已就緒：${totalW} 道詞語高亮題 + ${totalS} 道全句全析題（共 ${totalW + totalS} 題）`;
        }

        window.addEventListener("keydown", (e) => {
            const quizView = document.getElementById("quizView");
            if (!quizView || !quizView.classList.contains("active")) return;

            const q = this.activeQuestions[this.currentIndex];
            if (!q) return;

            if (e.key === "ArrowLeft") {
                e.preventDefault();
                this.prevQuestion();
            } else if (e.key === "ArrowRight") {
                e.preventDefault();
                this.nextQuestion();
            } else if (e.key === " " || e.code === "Space") {
                if (!this.revealedMap[q.id]) {
                    e.preventDefault();
                    this.revealAnswer();
                }
            } else if (e.key === "1") {
                if (this.revealedMap[q.id]) {
                    e.preventDefault();
                    this.markJudge(true);
                }
            } else if (e.key === "2") {
                if (this.revealedMap[q.id]) {
                    e.preventDefault();
                    this.markJudge(false);
                }
            }
        });
    }

    escapeHtml(str) {
        if (str === null || str === undefined) return "";
        return String(str)
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

    shuffle(arr) {
        const copy = [...arr];
        for (let i = copy.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [copy[i], copy[j]] = [copy[j], copy[i]];
        }
        return copy;
    }

